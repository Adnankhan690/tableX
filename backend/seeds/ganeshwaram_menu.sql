-- ---------------------------------------------------------------------------
-- 1. Retire what is no longer on the board. Categories first, then their names freed.
-- ---------------------------------------------------------------------------
UPDATE menu_category c
SET status = 'archived', updated_at = NOW()
FROM restaurant r, gw_target t
WHERE c.restaurant_id = r.id AND r.slug = t.slug
  AND c.uid NOT IN (SELECT uid FROM gw_category)
  AND c.status <> 'archived';

/*
    Freeing the NAME, not just the uid. menu_category carries UNIQUE (restaurant_id, name) and
    menu_item carries UNIQUE (restaurant_id, category_id, name), so a retired row keeping its name
    fails the insert below and rolls back the whole transaction. Only actual collisions are
    touched, and the NOT LIKE guard makes a second run a no-op.
*/
UPDATE menu_category c
SET name = left(c.name, 53) || ' [retired]', updated_at = NOW()
FROM restaurant r, gw_target t
WHERE c.restaurant_id = r.id AND r.slug = t.slug
  AND c.uid NOT IN (SELECT uid FROM gw_category)
  AND c.name NOT LIKE '% [retired]'
  AND c.name IN (SELECT name FROM gw_category);

-- ---------------------------------------------------------------------------
-- 2. Categories.
--
-- The WHERE on DO UPDATE is a tenant guard: uid is globally unique, so without it a collision
-- with another restaurant would quietly hand this restaurant's row to someone else's menu.
-- ---------------------------------------------------------------------------
INSERT INTO menu_category (uid, restaurant_id, name, description, sort_order, status,
                           created_at, updated_at)
SELECT v.uid, r.id, v.name, v.description, v.sort_order, 'active', NOW(), NOW()
FROM restaurant r
JOIN gw_target t ON t.slug = r.slug
CROSS JOIN gw_category v
ON CONFLICT (uid) DO UPDATE SET
    name        = EXCLUDED.name,
    description = EXCLUDED.description,
    sort_order  = EXCLUDED.sort_order,
    status      = 'active',
    updated_at  = NOW()
WHERE menu_category.restaurant_id = EXCLUDED.restaurant_id;

-- ---------------------------------------------------------------------------
-- 3. Retire the dishes that are gone, and free their names.
-- ---------------------------------------------------------------------------
UPDATE menu_item m
SET status = 'archived', is_available = FALSE, updated_at = NOW()
FROM restaurant r, gw_target t
WHERE m.restaurant_id = r.id AND r.slug = t.slug
  AND m.uid NOT IN (SELECT uid FROM gw_item)
  AND m.status <> 'archived';

UPDATE menu_item m
SET name = left(m.name, 117) || ' [retired]', updated_at = NOW()
FROM restaurant r, gw_target t
WHERE m.restaurant_id = r.id AND r.slug = t.slug
  AND m.uid NOT IN (SELECT uid FROM gw_item)
  AND m.name NOT LIKE '% [retired]'
  AND EXISTS (
      SELECT 1 FROM gw_item i
      JOIN menu_category c ON c.uid = i.category_uid AND c.restaurant_id = m.restaurant_id
      WHERE i.name = m.name AND c.id = m.category_id
  );

-- ---------------------------------------------------------------------------
-- 4. The dishes.
--
-- food_type is hardcoded 'veg' rather than carried per row. Ganeshwaram is a pure-veg house and
-- there is nothing else on the card; a per-row column would only be somewhere for a mistake to
-- hide. If they ever serve egg, this becomes a column in gw_item -- do not special-case it here.
--
-- is_available, rating_count, rating_sum, image_url and image_key are absent from DO UPDATE on
-- purpose: this file is the authority on what is on the menu and how it is described, and on
-- nothing else. spice_level IS updated, which means a re-run overwrites a correction made in the
-- admin app -- correct it here instead, or drop that one line once the kitchen has been through.
-- ---------------------------------------------------------------------------
INSERT INTO menu_item (uid, restaurant_id, category_id, name, description, price_minor,
                       food_type, spice_level, is_available, is_bestseller, prep_time_mins,
                       sort_order, status, created_at, updated_at)
SELECT v.uid, r.id, c.id, v.name, v.description, v.price_minor,
       'veg', v.spice_level, TRUE, v.is_bestseller, v.prep_time_mins,
       v.sort_order, 'active', NOW(), NOW()
FROM restaurant r
JOIN gw_target t ON t.slug = r.slug
CROSS JOIN gw_item v
JOIN menu_category c ON c.restaurant_id = r.id AND c.uid = v.category_uid
ON CONFLICT (uid) DO UPDATE SET
    category_id    = EXCLUDED.category_id,
    name           = EXCLUDED.name,
    description    = EXCLUDED.description,
    price_minor    = EXCLUDED.price_minor,
    food_type      = EXCLUDED.food_type,
    spice_level    = EXCLUDED.spice_level,
    is_bestseller  = EXCLUDED.is_bestseller,
    prep_time_mins = EXCLUDED.prep_time_mins,
    sort_order     = EXCLUDED.sort_order,
    status         = 'active',
    updated_at     = NOW()
WHERE menu_item.restaurant_id = EXCLUDED.restaurant_id;

-- ---------------------------------------------------------------------------
-- 5. Prove it landed. Counted inside the transaction and raised on a mismatch, so a partial load
-- rolls back rather than going live half-applied.
-- ---------------------------------------------------------------------------
DO $verify$
DECLARE
    rid      INT := (SELECT r.id FROM restaurant r JOIN gw_target t ON t.slug = r.slug);
    expected INT := (SELECT count(*) FROM gw_item);
    live INT; live_cats INT; retired INT; nonveg INT;
BEGIN
    SELECT count(*) INTO live      FROM menu_item     WHERE restaurant_id = rid AND status = 'active';
    SELECT count(*) INTO live_cats FROM menu_category WHERE restaurant_id = rid AND status = 'active';
    SELECT count(*) INTO retired   FROM menu_item     WHERE restaurant_id = rid AND status = 'archived';
    SELECT count(*) INTO nonveg    FROM menu_item
     WHERE restaurant_id = rid AND status = 'active' AND food_type <> 'veg';

    IF live <> expected THEN
        RAISE EXCEPTION 'expected % active dishes, found % -- rolled back, the live menu is unchanged',
            expected, live;
    END IF;

    -- A BACKSTOP, not the protection -- worth being clear about which is which.
    --
    -- The actual protection is that food_type is hardcoded 'veg' in the INSERT above, so a row
    -- flipped to non_veg by hand is corrected on the next run rather than caught here; verified
    -- by doing exactly that. This assertion therefore only fires if somebody later makes
    -- food_type a per-row column and gets a row wrong, which is precisely when it is wanted.
    -- Diners choose this restaurant for being pure veg; one wrong row is not a cosmetic error.
    IF nonveg > 0 THEN
        RAISE EXCEPTION '% non-veg dish(es) on a pure-veg menu -- rolled back', nonveg;
    END IF;

    RAISE NOTICE 'Ganeshwaram menu: % dishes across % categories, all veg (% retired).',
        live, live_cats, retired;
END
$verify$;

