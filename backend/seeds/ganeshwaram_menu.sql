-- Ganeshwaram -- full menu, transcribed from the seven printed pages.
--
-- Same shape as backend/seeds/jawahar_menu.sql, and the reasoning in that file's header applies
-- here unchanged: it touches only the menu, it refuses to run against the wrong database, and it
-- is a SYNC rather than an append -- anything this restaurant has that is not in this file is
-- archived, not deleted, because order_item.menu_item_id is ON DELETE RESTRICT (D8).
--
-- Preserved across a re-run, because this file is not the authority on any of it:
--   * is_available -- the "we ran out" toggle staff flip during service
--   * rating_count / rating_sum -- the review aggregate (migration 016)
--   * image_url / image_key -- photos uploaded through the admin app (D15)
--
-- WHAT IS DIFFERENT FROM JAWAHAR
--
-- 1. EVERY DISH IS VEGETARIAN. The restaurant is a pure-veg house -- its own logo reads
--    "veg food · sweets · snacks" -- and there is no meat or egg anywhere on the seven pages. So
--    food_type is 'veg' on all 357 rows. That is a fact off the card, not an assumption, and it
--    is worth stating because a single stray 'non_veg' here would be a serious error in a
--    restaurant whose customers choose it precisely for this.
--
-- 2. THE PRINTED ASTERISK IS CARRIED INTO THE DESCRIPTIONS. The menu footer defines it as
--    "available without onion and garlic also", which in this market is an ordering constraint
--    rather than a footnote -- it is why a satvik or Jain diner can eat here at all. The schema
--    has no column for it, so the dishes that carry it say so in their own description where a
--    diner will actually read it. If that ever becomes a filter, it should become a column.
--
-- 3. TIMED AND SEASONAL ITEMS SAY SO. Breakfast is 9:30-11:30 am (last order 11:00), tandoor
--    items may be unavailable 4-6 pm, and saag, gajar halwa and moong dal halwa are winter only.
--    All of that is in the description rather than enforced, because the schema has no opening
--    hours and inventing one here would be worse than telling the diner plainly.
--
-- TRANSCRIPTION NOTES -- read before running:
--   * The DESSERTS page is the one photographed at an angle, and its two price columns sit
--     visually offset from their names. The reading here follows each column top to bottom and is
--     self-consistent, but the sweets counter is where a wrong price costs real money. Have
--     somebody check that section against the card before the first service.
--   * Mineral Water and Soft Drink (250 ml / 750 ml) are priced "MRP" on the board. price_minor
--     is NOT NULL and a guessed figure would mis-bill a diner, so they are left out -- the lines
--     are ready to uncomment at the foot of the item list once a figure is decided.
--   * Items sold "(per kg)" are priced per kilogram. The cart multiplies quantity by price, so a
--     diner ordering 2 is billed for 2 kg. That is correct for a mithai counter but worth knowing
--     before somebody reports it as a bug.
--   * spice_level and prep_time_mins are NOT on the board. They are house defaults, set so the
--     diner card renders fully; the kitchen should correct them.
--
-- USAGE
--   psql "$DATABASE_URL" -v ON_ERROR_STOP=1 -f backend/seeds/ganeshwaram_menu.sql
--   make seed SEED_FILE=backend/seeds/ganeshwaram_menu.sql
--
-- The whole file is one transaction. A failure anywhere leaves the live menu untouched.

